"""
Name:        translate.py
Description: translates a Konami CPU program (the 052001 and the 053248, banked) into C, one C function per
             function and an instruction at a time: the translation scaffold of a game on Konami's CPU
Version:     0.1.0
Created:     06-11-2026
Modified:    06-11-2026
Author:      Sebastian Toyos

Usage: python tools/recompile.py [rom folder or .zip]   (the core's recompile.py runs this when the game's profile
       says TRANSLATOR = "konami_cpu.translate")
Writes build/generated/: program.h, program_NN.c and entries.c. Nothing it writes may be redistributed: it is the
game's code, translated from the user's own ROM.

The program is what the static analysis finds (konami_cpu/analysis.py and symbols.txt, no traces), place by place (a
bank's code at its offset in the program's region, the fixed program's at its own): a function starts at each
vector's handler, at each target of a call, at each place a jump or a call through memory or a register goes (what
the analysis follows into the tables), and at each func or code line of symbols.txt; code reached from none of them
starts one of its own. Every instruction becomes the C of its IR (konami_cpu/lift.py, written by
konami_cpu/emit_c.py), so the C does what MAME's core does, access by access; the C of the instructions that change
the flow is written here:
  - a branch or a jump to a fixed place is a goto inside the function, or a tail call to another function; a bank's
    code goes on in its own bank (no bank's code changes its bank: every SETLN is the fixed program's), and the
    fixed program's jumps into the window ask the runtime for the code there in the bank the CPU has;
  - a call (BSR, LBSR, JSR) pushes the return address, as the CPU does, and calls the C of its target (a call into
    the window from the fixed program, or through memory, asks the runtime, which finds it in the bank the CPU has);
    the runtime keeps the return addresses the calls wait for, and a call that comes back somewhere else returns
    from the caller too, until the function waiting for that address takes it up;
  - a return (RTS, RTI, PULLS and PULLU of the PC) leaves where it popped in cpu.pc and returns from the C function;
  - a jump through memory or a register asks the runtime: to a return address a call waits for, it is a return; to
    the start of a function, a tail call.
The board's frame runs where the game waits for one (the profile's FRAME_WAITS, frame timing: the runtime moves the
board on to its next VBLANK when the program finds nothing to do there), and an interrupt the board raised is taken
after that instruction, as MAME's core takes it at its next instruction; after the profile's FIRQ_POINT (where the
runtime lets the sprite DMA's FIRQ come), and after an instruction that can clear the CC's I or F (ANDCC, PULLS and
PULLU of the CC), which may let one through. Instructions take no time.
The board's own code takes the place of the game's where the profile's REPLACED_CODE says (the boot's ROM test:
the game has no ROM chips to add up): at its start the C calls the runtime's function and goes on where the game's
code would; the instructions it replaces are not written.
"""
import sys
from pathlib import Path

import game_profile  # noqa: E402  (the game's: its root, its ROM set, its settings)
import recompile  # noqa: E402  (the scaffold's base: how functions are split, named and shared)
from v60 import ir  # noqa: E402

from . import analysis  # noqa: E402
from . import disassembler as dis  # noqa: E402
from . import emit_c  # noqa: E402
from . import lift  # noqa: E402

ROOT = game_profile.ROOT
FUNCTIONS_PER_FILE = 150
# the vectors: FIRQ, IRQ, SWI, NMI, RESET (FFF6-FFFF; SWI2 and SWI3 the program leaves erased)
VECTORS = (0xFFF6, 0xFFF8, 0xFFFA, 0xFFFC, 0xFFFE)
# where the program waits for its next frame (frame timing: the runtime's frame.h), and where its IRQ handler takes
# the sprite DMA's FIRQ: places
FRAME_WAITS = set(getattr(game_profile, "FRAME_WAITS", ()))
FIRQ_POINT = getattr(game_profile, "FIRQ_POINT", None)
ANDCC, PULLS, PULLU = 0x3C, 0x0E, 0x0F
# the game's code the board's takes the place of: {start place: (the runtime's function, the place it goes on at)}
REPLACED_CODE = getattr(game_profile, "REPLACED_CODE", {})

HEADER = f"""/*
 * Generated by tools/recompile.py from the user's own ROM. Do not redistribute.
 * {game_profile.ROM_SET_TITLE}: {game_profile.CPU} program translated to C.
 */
"""


def const(value):
    return f"0x{value & 0xFFFF:04X}u"


def place_text(place):
    return f"0x{place:06X}u"


class Unsupported(Exception):
    """An instruction the translator cannot write."""


class Placed:
    """An instruction at its place"""

    def __init__(self, place, instruction):
        self.place = place
        self.instruction = instruction
        self.address = place
        self.flow = instruction.flow
        self.length = instruction.length
        self.text = instruction.text

    @property
    def bank(self):
        return analysis.bank_of(self.place)

    @property
    def cpu(self):
        return self.instruction.address & 0xFFFF

    @property
    def next_cpu(self):
        return (self.instruction.address + self.instruction.length) & 0xFFFF


class Program(recompile.Program):
    """The analysed program, split into functions ready to be written as C"""

    def __init__(self, image, symbols):
        self.image = image
        self.symbols = symbols
        self.analysis = analysis.Analysis(image, symbols)
        self.analysis.run()
        found = self.analysis
        self.placed = {place: Placed(place, instruction) for place, instruction in found.instructions.items()}
        fixed = found.view(None)
        entries = set(found.functions) | set(found.from_table)
        entries |= {analysis.place_of(None, fixed.r16(vector)) for vector in VECTORS}
        entries |= {address for address, symbol in symbols.items() if symbol.kind in ("func", "code")}
        self.entries = {place for place in entries if place in self.placed}

        self.bodies = {entry: self.walk(entry) for entry in sorted(self.entries)}
        covered = set().union(*self.bodies.values())
        replaced = {place for start, (_, resume) in REPLACED_CODE.items() for place in range(start + 1, resume)}
        self.orphans = sorted(place for place in self.placed if place not in covered and place not in replaced)
        while True:
            covered = set().union(*self.bodies.values())
            starts = [place for place in self.orphans if place not in covered]
            if not starts:
                break
            self.entries.add(starts[0])
            self.bodies[starts[0]] = self.walk(starts[0])
        self.split_shared_code()
        self.names = self.choose_names()

    def place_of(self, placed, cpu):
        """The place of a CPU address an instruction goes to: in its own bank in the window, or the fixed
        program's; None for the window from the fixed program (the bank is the CPU's then) or below it"""
        cpu &= 0xFFFF
        if cpu >= analysis.FIXED_CPU:
            return analysis.place_of(None, cpu)
        if cpu >= analysis.WINDOW and placed.bank is not None:
            return analysis.place_of(placed.bank, cpu)
        return None

    def successors(self, placed):
        """Places execution can go on at inside the same function"""
        if placed.place in REPLACED_CODE:
            return [REPLACED_CODE[placed.place][1]]
        flow = placed.flow
        following = []
        if flow in (dis.FLOW_NORMAL, dis.FLOW_BRANCH, dis.FLOW_CALL):
            following.append(placed.place + placed.length)
        if flow in (dis.FLOW_BRANCH, dis.FLOW_JUMP) and placed.instruction.target is not None:
            target = self.place_of(placed, placed.instruction.target)
            if target is not None:
                following.append(target)
        return following

    def walk(self, entry):
        body = {}
        stack = [entry]
        while stack:
            place = stack.pop()
            if place in body or (place != entry and place in self.entries):
                continue
            placed = self.placed.get(place)
            if placed is None:
                raise SystemExit(f"No decoded instruction at {place:06X} (function {entry:06X})")
            body[place] = placed
            stack += self.successors(placed)
        return body

    def choose_names(self):
        named = {address: symbol.name for address, symbol in self.symbols.items() if symbol.kind in ("func", "code")}
        names, used = {}, set()
        for entry in sorted(self.entries):
            name = named.get(entry, f"sub_{entry:06X}")
            if name in used:
                name = f"{name}_{entry:06X}"
            used.add(name)
            names[entry] = name
        return names


class FunctionWriter:
    """Writes one function as one C function"""

    def __init__(self, program, entry):
        self.program = program
        self.entry = entry
        self.body = program.bodies[entry]
        self.labels = set()

    def transfer(self, placed, cpu):
        """C that sends execution to CPU address 'cpu' from 'placed': a goto inside this function, a tail call, or the
        runtime's jump into the window"""
        target = self.program.place_of(placed, cpu)
        if target is None:
            return f"{{ konami_jump({const(cpu)}, {place_text(placed.place)}); return; }}"
        if target != self.entry and target in self.program.entries:
            return f"{{ {self.program.names[target]}(); return; }}"
        if target not in self.body:
            raise Unsupported(f"jump to {target:06X}, outside function {self.entry:06X}")
        self.labels.add(target)
        return f"goto L_{target:06X};"

    def call(self, placed, control, printer):
        """A call: the return address is pushed (the lifted statements did), the callee runs, and execution goes on
        here if it came back to the return address"""
        lines = [f"konami_calls_push({const(placed.next_cpu)});"]
        target = self.program.place_of(placed, control.target) if control.target is not None else None
        if target is not None:
            if target not in self.program.entries:
                raise Unsupported(f"call to {target:06X}, which starts no function")
            lines.append(f"{self.program.names[target]}();")
        else:
            address = const(control.target) if control.target is not None else printer.expr(control.address)
            lines.append(f"konami_call({address}, {place_text(placed.place)});")
        lines.append(f"if (!konami_returned_to({const(placed.next_cpu)}, {place_text(placed.place)})) return;")
        return lines

    def instruction_lines(self, placed):
        if placed.place in REPLACED_CODE:
            # the board's code in place of the game's, which goes on where the game's would
            function, resume = REPLACED_CODE[placed.place]
            return ["{", f"\t{function}();", f"\t{self.transfer(placed, analysis.cpu_of(resume))}", "}"]
        try:
            lifter = lift.lift(self.program.analysis.view(placed.bank), placed.cpu)
        except lift.Unsupported as problem:
            raise Unsupported(str(problem)) from problem
        if lifter.length != placed.length:
            raise Unsupported(f"{placed.place:06X}: the lift reads {lifter.length} bytes, the decoder {placed.length}")
        printer = emit_c.Printer()
        lines = [printer.statement(statement) for statement in lifter.statements]
        # (interrupts the board raised, or the CC now lets through, come after the instruction)
        waits = placed.place in FRAME_WAITS
        firq_point = placed.place == FIRQ_POINT
        unmasks = lifter.opcode == ANDCC or lifter.opcode in (PULLS, PULLU) \
            and placed.instruction.operands and "CC" in placed.instruction.operands[0].registers
        interrupts = waits or firq_point or unmasks
        if waits:
            lines.insert(0, f"konami_frame_wait({const(placed.cpu)});")
        if firq_point:
            lines.insert(0, "konami_firq_point();")

        control = lifter.control
        if control.kind == "goto":
            if interrupts:
                lines.append(f"konami_take_interrupts({const(control.target)});")
            lines.append(self.transfer(placed, control.target))
        elif control.kind == "branch":
            taken = [self.transfer(placed, control.target)]
            if interrupts:
                taken.insert(0, f"konami_take_interrupts({const(control.target)});")
            lines += [f"if ({printer.expr(control.condition)})", "{"] + [f"\t{line}" for line in taken] + ["}"]
            if interrupts:
                lines.append(f"konami_take_interrupts({const(placed.next_cpu)});")
        elif control.kind == "call":
            lines += self.call(placed, control, printer)
        elif control.kind == "jump":
            lines += [f"konami_jump({printer.expr(control.address)}, {place_text(placed.place)});", "return;"]
        elif control.kind == "return":
            lines.append(f"cpu.pc = {printer.expr(control.address)};")
            if interrupts:
                lines.append("konami_take_interrupts(cpu.pc);")
            lines.append("return;")
        elif interrupts:
            lines.append(f"konami_take_interrupts({const(placed.next_cpu)});")
        if not lines:
            return ["/* nothing to do */"]
        if len(lines) == 1:
            return lines
        return ["{"] + [f"\t{line}" for line in lines] + ["}"]

    def write(self):
        order = [self.entry] + sorted(place for place in self.body if place != self.entry)
        chunks = []
        for position, place in enumerate(order):
            placed = self.body[place]
            lines = [f"/* {place:06X}  {placed.text} */"]
            lines += self.instruction_lines(placed)
            if placed.flow in (dis.FLOW_NORMAL, dis.FLOW_BRANCH, dis.FLOW_CALL) and place not in REPLACED_CODE:
                following = place + placed.length
                upcoming = order[position + 1] if position + 1 < len(order) else None
                if following != upcoming or following in self.program.entries:
                    lines.append(self.transfer(placed, placed.next_cpu))
            chunks.append((place, lines))
        text = [f"void {self.program.names[self.entry]}(void)", "{"]
        for place, lines in chunks:
            if place in self.labels:
                text.append(f"L_{place:06X}:")
            text += [f"\t{line}" for line in lines]
        text.append("}")
        return "\n".join(text)


def main(arguments):
    if not FRAME_WAITS or FIRQ_POINT is None:
        raise SystemExit("game_profile.py: no FRAME_WAITS or FIRQ_POINT (where the program waits for its frame)")
    source = Path(arguments[0]) if arguments else ROOT / "rom"
    image = game_profile.rom.build_program(game_profile.rom.load_set(source))
    symbols = analysis.load_symbols(ROOT / "symbols.txt")
    program = Program(image, symbols)
    missing = [place for place in FRAME_WAITS | {FIRQ_POINT} if place not in program.placed]
    if missing:
        raise SystemExit(f"game_profile.py: {', '.join(f'{place:06X}' for place in missing)} no instruction of the "
                         "program")

    out_dir = ROOT / "build" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("program_*.c"):
        old.unlink()
    entries = sorted(program.entries)
    prototypes = [f"void {program.names[entry]}(void);" for entry in entries]
    (out_dir / "program.h").write_text(
        HEADER + f"#ifndef {game_profile.GUARD}_PROGRAM_H\n#define {game_profile.GUARD}_PROGRAM_H\n\n"
        + "".join(f"void {function}(void);    /* the board's, in place of {start:06X} */\n"
                  for start, (function, _) in sorted(REPLACED_CODE.items()))
        + "\n".join(prototypes) + "\n\n#endif\n", encoding="ascii")

    failures = []
    for number, first in enumerate(range(0, len(entries), FUNCTIONS_PER_FILE)):
        functions = []
        for entry in entries[first:first + FUNCTIONS_PER_FILE]:
            try:
                functions.append(FunctionWriter(program, entry).write())
            except Unsupported as problem:
                failures.append((entry, str(problem)))
        text = HEADER + '#include "konami/cpu.h"\n#include "konami/ops.h"\n#include "program.h"\n\n'
        (out_dir / f"program_{number:02}.c").write_text(text + "\n\n".join(functions) + "\n", encoding="ascii")

    table = [f"\t{{ {place_text(entry)}, {program.names[entry]} }}," for entry in entries]
    (out_dir / "entries.c").write_text(
        HEADER + '#include "konami/code.h"\n#include "program.h"\n\n'
        + "const konami_code_entry konami_code_entries[] =\n{\n" + "\n".join(table) + f"\n}};\n\nconst size_t konami_code_entry_count = {len(entries)};\n", encoding="ascii")

    instructions = sum(len(body) for body in program.bodies.values())
    print(f"functions:      {len(entries)}")
    print(f"instructions:   {instructions} written ({len(program.placed)} distinct)")
    print(f"orphan starts:  {len(program.orphans)}")
    print(f"not translated: {len(failures)}")
    for entry, problem in failures[:20]:
        print(f"  {entry:06X}  {problem}")
    print(f"Output: {out_dir}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
