"""
Name:        translate.py
Description: translates a 68000 program into C, one C function per function and an instruction at a time:
             the translation scaffold of a game on a 68000
Version:     0.1.0
Created:     29-10-2026
Modified:    29-10-2026
Author:      Sebastian Toyos

Usage: python tools/recompile.py [rom folder or .zip]   (the core's recompile.py runs this when the game's
       profile says TRANSLATOR = "m68000.translate")
Writes build/generated/: program.h, program_NN.c and entries.c. Nothing it writes may be redistributed: it is
the game's code, translated from the user's own ROM.

The program is what the static analysis finds (m68000/analysis.py and symbols.txt, no traces). A function
starts at each vector's handler, at each target of a call, at each place a jump or a call through a register
can go (what the analysis follows the address registers to: the tables of handlers, the addresses loaded
before), at each entry of a table of code, and at each func or code line of symbols.txt; code reached from
none of them starts one of its own. Every instruction becomes the C of its IR (m68000/lift.py, written by
m68000/emit_c.py), so the C does what MAME's 68000 core does, bus cycle by bus cycle; the C of the
instructions that change the flow is written here:
  - a branch or a jump to a fixed place is a goto inside the function, or a tail call to another function;
  - a call (BSR, JSR) pushes the return address, as the 68000 does, and calls the C of its target (a call
    through a register asks the runtime for it); the runtime keeps the return addresses the calls wait for,
    and a call that comes back somewhere else (the callee dropped its return address, or went back through
    a register) returns from the caller too, until the function waiting for that address takes it up;
  - a return (RTS, RTR, RTE) leaves where it popped in cpu.pc and returns from the C function;
  - a jump through a register asks the runtime: to a return address a call waits for, it is a return; to
    the start of a function, a tail call.
The board's frame runs where the game's main loop idles (the profile's FRAME_WAIT: the instruction that
finds nothing to do, where the runtime moves the board to its next VBLANK when the program idles), and an
interrupt the board raised is taken after that instruction, as MAME's core takes it; after an instruction
that writes the status register too, which may unmask one. Instructions take no time.
"""
import sys
from pathlib import Path

import game_profile  # noqa: E402  (the game's: its root, its ROM set, its settings)
import recompile  # noqa: E402  (the V60's scaffold: how functions are split, named and shared)
from v60 import ir  # noqa: E402

from . import analysis  # noqa: E402
from . import disassembler as dis  # noqa: E402
from . import emit_c  # noqa: E402
from . import lift  # noqa: E402

ROOT = game_profile.ROOT
FUNCTIONS_PER_FILE = 120
VECTORS = range(1, 48)
# the main loop's idle point: the instruction that finds nothing to do (TMNT: 0013CE, the empty command queue)
FRAME_WAIT = getattr(game_profile, "FRAME_WAIT", None)
# the game's code the board's runtime puts its own in place of: {start: (the runtime's function, where the
# game's code goes on)} (TMNT: the boot's ROM test, which sums chips the game does not have)
REPLACED_CODE = getattr(game_profile, "REPLACED_CODE", {})

HEADER = f"""/*
 * Generated by tools/recompile.py from the user's own ROM. Do not redistribute.
 * {game_profile.ROM_SET_TITLE}: {game_profile.CPU} program translated to C.
 */
"""


def key(address):
    return address & 0xFFFFFF


def const(value):
    return f"0x{value & 0xFFFFFFFF:06X}u"


class Unsupported(Exception):
    """An instruction the translator cannot write."""


class Found(analysis.Analysis):
    """The static analysis, keeping where the jumps and calls through registers can go"""

    def reset(self):
        super().reset()
        self.computed_targets = set()
        self.in_computed = False

    def computed(self, instruction, state, block):
        self.in_computed = True
        try:
            super().computed(instruction, state, block)
        finally:
            self.in_computed = False

    def enter(self, address, state=None, kind=None):
        if self.in_computed:
            self.computed_targets.add(address & 0xFFFFFF)
        super().enter(address, state, kind)


class Program(recompile.Program):
    """The analysed 68000 program, split into functions ready to be written as C."""

    def __init__(self, image, symbols):
        self.image = image
        self.mem = dis.FlatMemory(image)
        self.symbols = symbols
        self.analysis = Found(image, symbols)
        self.analysis.run()
        instructions = self.analysis.instructions

        entries = set(self.analysis.functions) | self.analysis.computed_targets
        for vector in VECTORS:
            entries.add(key(self.mem.r32(4 * vector)))
        for table in self.analysis.code_tables.values():
            entries.update(table)
        for table in self.analysis.field_tables.values():
            entries.update(table)
        entries.update(address for address, symbol in symbols.items() if symbol.kind in ("func", "code"))
        self.entries = {address for address in entries if address in instructions}

        self.bodies = {entry: self.walk(entry) for entry in sorted(self.entries)}
        # code that no function reaches gets an entry of its own
        covered = set().union(*self.bodies.values())
        self.orphans = sorted(address for address in instructions if address not in covered)
        while True:
            covered = set().union(*self.bodies.values())
            starts = [address for address in self.orphans if address not in covered]
            if not starts:
                break
            self.entries.add(starts[0])
            self.bodies[starts[0]] = self.walk(starts[0])
        self.split_shared_code()
        self.names = self.choose_names()

    def successors(self, instruction):
        """Addresses execution can go on at inside the same function"""
        flow = instruction.flow
        following = []
        if flow in (dis.FLOW_NORMAL, dis.FLOW_BRANCH, dis.FLOW_CALL):
            following.append(key(instruction.address + instruction.length))
        if flow in (dis.FLOW_BRANCH, dis.FLOW_JUMP) and instruction.target is not None:
            following.append(key(instruction.target))
        return following


class FunctionWriter:
    """Writes one 68000 function as one C function."""

    def __init__(self, program, entry):
        self.program = program
        self.entry = entry
        self.body = program.bodies[entry]
        self.labels = set()

    def transfer(self, target):
        """C that sends execution to 'target': a goto inside this function, or a tail call."""
        target = key(target)
        if target != self.entry and target in self.program.entries:
            return f"{{ {self.program.names[target]}(); return; }}"
        if target not in self.body:
            raise Unsupported(f"jump to {target:06X}, outside function {self.entry:06X}")
        self.labels.add(target)
        return f"goto L_{target:06X};"

    def call(self, control, next_address, address, printer):
        """A call: the return address is pushed (the lifted statements did), the callee runs, and execution
        goes on here if it came back to the return address"""
        lines = [f"m68k_calls_push({const(next_address)});"]
        if control.target is not None:
            target = key(control.target)
            if target not in self.program.entries:
                raise Unsupported(f"call to {target:06X}, which starts no function")
            lines.append(f"{self.program.names[target]}();")
        else:
            lines.append(f"m68k_call({printer.expr(control.address)}, {const(address)});")
        lines.append(f"if (!m68k_returned_to({const(next_address)}, {const(address)})) return;")
        return lines

    def instruction_lines(self, instruction):
        address = instruction.address
        next_address = key(address + instruction.length)
        if address in REPLACED_CODE:
            # the runtime's code in place of the game's, which goes on where the game's would
            function, resume = REPLACED_CODE[address]
            return ["{", f"\t{function}();", f"\t{self.transfer(resume)}", "}"]
        try:
            lifter = lift.lift(instruction)
        except lift.Unsupported as problem:
            raise Unsupported(str(problem)) from problem
        printer = emit_c.Printer()
        lines = []
        writes_sr = False
        for statement in lifter.statements:
            if isinstance(statement, ir.Effect) and statement.name == "exception_if":
                condition, vector, pc = statement.args
                take = f"if (!m68k_exception({vector.value}u, {const(pc.value)}, {const(address)})) return;"
                body = [take, self.transfer(pc.value)]
                if isinstance(condition, ir.Const):
                    lines += body
                else:
                    lines += [f"if ({printer.expr(condition)})", "{"] + [f"\t{line}" for line in body] + ["}"]
                continue
            if isinstance(statement, ir.Effect) and statement.name == "write_sr":
                writes_sr = True
            lines.append(printer.statement(statement))

        control = lifter.control
        if control.kind == "goto":
            lines.append(self.transfer(control.target))
        elif control.kind == "branch":
            lines += [f"if ({printer.expr(control.condition)})", f"\t{self.transfer(control.target)}"]
        elif control.kind == "call":
            lines += self.call(control, next_address, address, printer)
        elif control.kind == "jump":
            lines += [f"m68k_jump({printer.expr(control.address)}, {const(address)});", "return;"]
        elif control.kind == "return":
            lines += [f"cpu.pc = {printer.expr(control.address)};", "return;"]
        elif writes_sr or address == FRAME_WAIT:
            # an interrupt the board raised (or one the new mask lets through) comes after the instruction
            lines.append(f"m68k_take_interrupts({const(next_address)});")
        if address == FRAME_WAIT:
            # the main loop finds nothing to do: the board moves on to its next frame
            lines.insert(0, "program_frame_wait();")
        if not lines:
            return ["/* nothing to do */"]
        if len(lines) == 1:
            return lines
        return ["{"] + [f"\t{line}" for line in lines] + ["}"]

    def write(self):
        order = [self.entry] + sorted(address for address in self.body if address != self.entry)
        chunks = []
        for position, address in enumerate(order):
            instruction = self.body[address]
            lines = [f"/* {address:06X}  {instruction.text} */"]
            lines += self.instruction_lines(instruction)
            if instruction.flow in (dis.FLOW_NORMAL, dis.FLOW_BRANCH, dis.FLOW_CALL):
                following = key(address + instruction.length)
                upcoming = order[position + 1] if position + 1 < len(order) else None
                if following != upcoming or following in self.program.entries:
                    lines.append(self.transfer(following))
            chunks.append((address, lines))

        text = [f"void {self.program.names[self.entry]}(void)", "{"]
        for address, lines in chunks:
            if address in self.labels:
                text.append(f"L_{address:06X}:")
            text += [f"\t{line}" for line in lines]
        text.append("}")
        return "\n".join(text)


def main(arguments):
    if FRAME_WAIT is None:
        raise SystemExit("game_profile.py: no FRAME_WAIT (the main loop's idle point)")
    source = Path(arguments[0]) if arguments else ROOT / "rom"
    image = game_profile.rom.build_program(game_profile.rom.load_set(source))
    symbols = analysis.load_symbols(ROOT / "symbols.txt")
    program = Program(image, symbols)
    if FRAME_WAIT not in program.analysis.instructions:
        raise SystemExit(f"game_profile.py: FRAME_WAIT {FRAME_WAIT:06X} is no instruction of the program")

    out_dir = ROOT / "build" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("program_*.c"):
        old.unlink()

    entries = sorted(program.entries)
    prototypes = [f"void {program.names[entry]}(void);" for entry in entries]
    (out_dir / "program.h").write_text(
        HEADER + f"#ifndef {game_profile.GUARD}_PROGRAM_H\n#define {game_profile.GUARD}_PROGRAM_H\n\n"
        + f"#define PROGRAM_FRAME_WAIT {const(FRAME_WAIT)}\n\n"
        + "".join(f"void {function}(void);    /* the runtime's, in place of {start:06X} */\n"
                  for start, (function, _) in sorted(REPLACED_CODE.items()))
        + "\n" + "\n".join(prototypes) + "\n\n#endif\n",
        encoding="ascii")

    failures = []
    for number, first in enumerate(range(0, len(entries), FUNCTIONS_PER_FILE)):
        functions = []
        for entry in entries[first:first + FUNCTIONS_PER_FILE]:
            try:
                functions.append(FunctionWriter(program, entry).write())
            except Unsupported as problem:
                failures.append((entry, str(problem)))
        text = HEADER + '#include "m68000/registers.h"\n#include "m68000/ops.h"\n#include "program.h"\n\n'
        (out_dir / f"program_{number:02}.c").write_text(text + "\n\n".join(functions) + "\n", encoding="ascii")

    table = [f"\t{{ {const(entry)}, {program.names[entry]} }}," for entry in entries]
    (out_dir / "entries.c").write_text(
        HEADER + '#include "m68000/code.h"\n#include "program.h"\n\nconst m68k_code_entry m68k_code_entries[] =\n{\n'
        + "\n".join(table) + f"\n}};\n\nconst size_t m68k_code_entry_count = {len(entries)};\n", encoding="ascii")

    instructions = sum(len(body) for body in program.bodies.values())
    print(f"functions:      {len(entries)}")
    print(f"instructions:   {instructions} written ({len(program.analysis.instructions)} distinct)")
    print(f"orphan starts:  {len(program.orphans)}")
    print(f"not translated: {len(failures)}")
    for entry, problem in failures[:20]:
        print(f"  {entry:06X}  {problem}")
    print(f"Output: {out_dir}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
